const posts={
    username:"Shashank",
    content:"Hello World",
    likes:100,
    repost:50,
    tags:["#hello","#world"] 
}

// get values of the posts object
console.log(posts.username); // this will print "Shashank"
console.log(posts.content); // this will print "Hello World"
console.log(posts.likes); // this will print 100
console.log(posts.repost); // this will print 50
console.log(posts.tags); // this will print ["#hello","#world"] 

